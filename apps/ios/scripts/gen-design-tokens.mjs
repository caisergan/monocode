#!/usr/bin/env node
// @monocode/design → MonoDesign/Sources/MonoDesign/Generated/Tokens.swift
// (16 §16.3), and the desktop's project mascots (projectMascots.ts) →
// Generated/Mascots.swift. Runs the package's TypeScript, so the Swift values are the
// values the desktop parity test checks. `--check` fails when the file on
// disk is stale instead of writing it.

import { build } from "esbuild";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { tmpdir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");
const out = join(here, "../Packages/MonoDesign/Sources/MonoDesign/Generated/Tokens.swift");
const mascotsOut = join(here, "../Packages/MonoDesign/Sources/MonoDesign/Generated/Mascots.swift");

async function loadDesign(entry = join(repo, "packages/design/src/index.ts")) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: "esm",
    platform: "node",
    write: false,
  });
  const file = join(tmpdir(), `monocode-design-${process.pid}-${entry.split("/").pop()}.mjs`);
  await writeFile(file, result.outputFiles[0].text);
  try {
    return await import(pathToFileURL(file).href);
  } finally {
    await rm(file);
  }
}

const design = await loadDesign();
const { palette, parseColor, TINT, ACCENT_HSL, PROJECT_COLORS, USER_ACCENT_PRESETS, MOTION, RADII, TYPE } = design;

function number(value) {
  if (!Number.isFinite(value)) throw new Error(`not a number: ${value}`);
  return String(value);
}

/** "#rrggbb", "rgba(r,g,b,a)" or "hsl(h s% l%)" → MonoColor(...). */
function color(value) {
  const rgba = value.match(/^rgba\((\d+),(\d+),(\d+),([\d.]+)\)$/);
  if (rgba) return `MonoColor(${rgba[1]}, ${rgba[2]}, ${rgba[3]}, ${number(Number(rgba[4]))})`;
  if (/^#[0-9a-f]{6}$/i.test(value) || value.startsWith("hsl(")) {
    const [r, g, b] = parseColor(value);
    return `MonoColor(${r}, ${g}, ${b})`;
  }
  throw new Error(`unknown colour: ${value}`);
}

const typeName = (key) => key[0].toUpperCase() + key.slice(1);
const field = (key) => (key === "default" ? "`default`" : key);

/** The palette's shape becomes nested structs; colours become MonoColor. */
function paletteTypes(value, name, indent) {
  const pad = "  ".repeat(indent);
  const lines = [`${pad}public struct ${name}: Sendable, Equatable {`];
  for (const [key, child] of Object.entries(value)) {
    if (typeof child === "function" || key === "scheme") continue;
    if (typeof child === "object") {
      lines.push(...paletteTypes(child, typeName(key), indent + 1));
      lines.push(`${pad}  public let ${field(key)}: ${typeName(key)}`);
    } else {
      lines.push(`${pad}  public let ${field(key)}: MonoColor`);
    }
  }
  lines.push(`${pad}}`);
  return lines;
}

function paletteValue(value, name, indent) {
  const pad = "  ".repeat(indent);
  const args = [];
  for (const [key, child] of Object.entries(value)) {
    if (typeof child === "function" || key === "scheme") continue;
    if (typeof child === "object") args.push(`${pad}  ${key}: ${paletteValue(child, `${name}.${typeName(key)}`, indent + 1).trimStart()}`);
    else args.push(`${pad}  ${key}: ${color(child)}`);
  }
  return `${pad}${name}(\n${args.join(",\n")}\n${pad})`;
}

const dark = palette({ scheme: "dark" });
const light = palette({ scheme: "light" });
if (JSON.stringify(Object.keys(dark)) !== JSON.stringify(Object.keys(light))) throw new Error("dark and light palettes differ in shape");

const range = (r) => `TintRange(min: ${number(r.min)}, max: ${number(r.max)}, default: ${number(r.default)})`;
const bezier = (p) => `CubicBezier(${p.map(number).join(", ")})`;

const swift = `// Generated by apps/ios/scripts/gen-design-tokens.mjs from @monocode/design.
// Do not edit; run \`node apps/ios/scripts/gen-design-tokens.mjs\`.

public enum Tokens {
  /// Desktop: appearance.ts THEME_*_DEFAULT and ranges.
  public enum Tint {
    public static let hue = ${range(TINT.hue)}
    public static let saturation = ${range(TINT.saturation)}
    public static let darkLightness = ${range(TINT.darkLightness)}
  }

  /// Desktop: --color-accent, as hue, saturation and lightness.
  public static let accentHSL: (hue: Double, saturation: Double, lightness: Double) = (${ACCENT_HSL.map(number).join(", ")})

  /// Desktop: tabGroups.ts TAB_GROUP_COLORS (index 0 is neutral).
  public static let projectColors: [MonoColor] = [
${PROJECT_COLORS.map((c) => `    ${color(c)},`).join("\n")}
  ]

  public enum UserAccent {
${Object.entries(USER_ACCENT_PRESETS).map(([k, v]) => `    public static let ${k} = ${color(v)}`).join("\n")}
  }

  /// Desktop: --motion-*. Durations in milliseconds.
  public enum Motion {
    public static let easeOut = ${bezier(MOTION.easeOut)}
    public static let tabEaseOut = ${bezier(MOTION.tabEaseOut)}
${Object.entries(MOTION).filter(([, v]) => typeof v === "number").map(([k, v]) => `    public static let ${k}: Double = ${number(v)}`).join("\n")}
  }

  /// Radii (11 §11.4), in points.
  public enum Radius {
${Object.entries(RADII).map(([k, v]) => `    public static let ${k}: Double = ${number(v)}`).join("\n")}
  }

  /// Mobile type scale (11 §11.3): size and line height in points.
  public enum TypeScale {
${Object.entries(TYPE).map(([k, v]) => `    public static let ${k} = TypeRole(size: ${number(v.size)}, line: ${number(v.line)})`).join("\n")}
  }

  /// palette() at the default tint, for each scheme.
  public static let dark = ${paletteValue(dark, "Palette", 1).trimStart()}

  public static let light = ${paletteValue(light, "Palette", 1).trimStart()}
}

${paletteTypes(dark, "Palette", 0).join("\n")}
`;

const mascots = await loadDesign(join(repo, "src/features/projects/model/projectMascots.ts"));
const sampleIds = ["p-app", "p-api", "my-app", "monocode", "s-auth", "Review the auth module"];
const rows = (frame) => `[${frame.map((row) => JSON.stringify(row)).join(", ")}]`;
const mascotSwift = `// Generated by apps/ios/scripts/gen-design-tokens.mjs from the desktop's
// src/features/projects/model/projectMascots.ts. Do not edit.

extension Mascots {
  /// 8 × 8 sprites: "#" paints the project colour, "." is a hole. \`talk\` is
  /// swapped in while the project has a turn running.
  public static let all: [Sprite] = [
${mascots.PROJECT_MASCOTS.map((m) => `    Sprite(name: ${JSON.stringify(m.name)}, rest: ${rows(m.rest)}, talk: ${rows(m.talk)}),`).join("\n")}
  ]

  /// projectMascot() and projectColor() for a few ids, for the parity test.
  static let samples: [(id: String, mascot: String, colorIndex: Int)] = [
${sampleIds.map((id) => `    (${JSON.stringify(id)}, ${JSON.stringify(mascots.projectMascot(id).name)}, ${PROJECT_COLORS.indexOf(design.projectColor(id))}),`).join("\n")}
  ]
}
`;

const check = process.argv.includes("--check");
let stale = false;
for (const [path, text] of [[out, swift], [mascotsOut, mascotSwift]]) {
  const previous = await readFile(path, "utf8").catch(() => "");
  if (previous === text) continue;
  if (check) {
    console.error(`${path} is out of date; run node apps/ios/scripts/gen-design-tokens.mjs`);
    stale = true;
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, text);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
